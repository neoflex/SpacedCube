"""Build the app into dist/ (a static site: serve it over HTTPS from any host).

src/ is copied as is (no bundling: the browser loads the ES modules directly). The build adds:
  config.js      deployment settings, from environment variables (GitHub Actions variables in CI)
  privacy.html   the privacy page, filled in from the same variables
  icons          drawn by tools/icons.py
  sw.js          with the list of files to cache and a version hash

Environment variables (all optional; without SUPABASE_URL the app keeps progress in the browser only):
  SUPABASE_URL               https://<project>.supabase.co
  SUPABASE_PUBLISHABLE_KEY   the project's publishable (or legacy anon) key; public by design
  ALLOW_SIGNUP               "true": an unknown email creates an account on first sign-in
  TURNSTILE_SITE_KEY         Cloudflare Turnstile site key (public); empty = no check on the sign-in form
  PRIVACY_OPERATOR           who runs this copy, e.g. "Jane Doe, Luxembourg"
  PRIVACY_CONTACT_EMAIL      address for privacy requests
  PRIVACY_DATA_LOCATION      where Supabase stores the data, e.g. "Servers in Ireland (EU)."
  PRIVACY_EMAIL_PROVIDER     who sends the sign-in emails, e.g. "Brevo (EU)"
  PRIVACY_HOSTING            who hosts the files (default: GitHub Pages)
  REPOSITORY_URL             source code link in the footer (in GitHub Actions: this repository, automatically)
"""
import argparse, hashlib, html, json, os, pathlib, re, shutil, sys
from urllib.parse import urlsplit

root = pathlib.Path(__file__).parent
src = root / 'src'
ap = argparse.ArgumentParser(description='Build the app into a static site.')
ap.add_argument('--out', default=str(root / 'dist'), help='output directory (default: dist/)')
dist = pathlib.Path(ap.parse_args().out)
sys.path.insert(0, str(root / 'tools'))
import icons  # noqa: E402


def env(name, default=''):
    return os.environ.get(name, '').strip() or default


def truthy(v):
    return v.lower() in ('1', 'true', 'yes', 'on')


if dist.exists():
    shutil.rmtree(dist)
shutil.copytree(src, dist)

# Deployment settings.
config = {
    'supabaseUrl': env('SUPABASE_URL'),
    'supabaseKey': env('SUPABASE_PUBLISHABLE_KEY'),
    'allowSignup': truthy(env('ALLOW_SIGNUP')),
    'turnstileSiteKey': env('TURNSTILE_SITE_KEY'),
}
if bool(config['supabaseUrl']) != bool(config['supabaseKey']):
    sys.exit('Set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY, or neither.')
if config['supabaseUrl']:
    u = urlsplit(config['supabaseUrl'])
    if u.scheme not in ('https', 'http') or not u.netloc or u.path not in ('', '/'):
        sys.exit('SUPABASE_URL must look like https://<project>.supabase.co')
(dist / 'config.js').write_text(
    '// Generated by build.py from environment variables. Do not edit.\n'
    f'window.SPACEDCUBE_CONFIG = {json.dumps(config, indent=2)};\n')

# Content Security Policy, as a <meta> tag (GitHub Pages cannot send headers). Scripts and
# connections only to this site, the sync server and, when used, Cloudflare Turnstile.
# Inline style attributes are allowed (the views use a few); inline scripts are not.
turnstile = 'https://challenges.cloudflare.com' if config['turnstileSiteKey'] else ''
supa_origin = '{0.scheme}://{0.netloc}'.format(urlsplit(config['supabaseUrl'])) if config['supabaseUrl'] else ''
policy = {
    'default-src': ["'self'"],
    'script-src': ["'self'", turnstile],
    'style-src': ["'self'", "'unsafe-inline'"],
    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],
    'connect-src': ["'self'", supa_origin],
    'frame-src': [turnstile or "'none'"],
    'worker-src': ["'self'"],
    'manifest-src': ["'self'"],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
}
csp = '; '.join(k + ' ' + ' '.join(v for v in vals if v) for k, vals in policy.items())
CSP_PRIVACY = "default-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'none'; object-src 'none'; base-uri 'self'"
def add_csp(path, value):
    page = path.read_text()
    assert '<!--@CSP@-->' in page, f'{path.name} has no CSP marker'
    assert '"' not in value
    path.write_text(page.replace('<!--@CSP@-->', f'<meta http-equiv="Content-Security-Policy" content="{value}">'))
add_csp(dist / 'index.html', csp)

# Privacy page.
sync = bool(config['supabaseUrl'])
contact = env('PRIVACY_CONTACT_EMAIL')
values = {
    'OPERATOR': html.escape(env('PRIVACY_OPERATOR', 'the people who published it')),
    'CONTACT': f'<a href="mailto:{html.escape(contact)}">{html.escape(contact)}</a>' if contact else 'Ask the people who run this site.',
    'DATA_LOCATION': html.escape(env('PRIVACY_DATA_LOCATION')),
    'EMAIL_PROVIDER': html.escape(env('PRIVACY_EMAIL_PROVIDER', 'The email service of the sync server')),
    'HOSTING': html.escape(env('PRIVACY_HOSTING', 'GitHub Pages (GitHub, United States, under the EU-US Data Privacy Framework)')),
}
page = (src / 'privacy.html').read_text()
page = re.sub(r'\n<!-- Template:.*?-->', '', page)
for block, keep in (('SYNC', sync), ('TURNSTILE', sync and bool(config['turnstileSiteKey']))):
    pattern = rf'<!--IF {block}-->(.*?)<!--END {block}-->'
    page = re.sub(pattern, (lambda m: m.group(1)) if keep else '', page, flags=re.S)
for k, v in values.items():
    page = page.replace('{{' + k + '}}', v)
assert '{{' not in page and '<!--IF' not in page, 'unfilled privacy template'
(dist / 'privacy.html').write_text(page)
add_csp(dist / 'privacy.html', CSP_PRIVACY)

icons.write_all(dist)

# Footer: source code and issue links (the repository this build comes from), and the privacy page.
repo = env('REPOSITORY_URL')
if not repo and env('GITHUB_REPOSITORY'):
    repo = env('GITHUB_SERVER_URL', 'https://github.com') + '/' + env('GITHUB_REPOSITORY')
repo = repo.rstrip('/')
if repo and not re.match(r'^https://[^\s"<>]+$', repo):
    sys.exit('REPOSITORY_URL must be an https:// address')
links = ([f'<a href="{html.escape(repo)}">Source code</a>', f'<a href="{html.escape(repo)}/issues">Report a problem or suggest an idea</a>'] if repo else []) \
    + ['<a href="privacy.html">Privacy</a>']
footer = ('<footer class="foot"><p>SpacedCube is free and open source (MIT licence). '
          + '<span class="foot-links">' + ''.join(f'<span>{a}</span>' for a in links) + '</span></p></footer>')
index_path = dist / 'index.html'
index_path.write_text(index_path.read_text().replace('<!--@FOOTER@-->', footer))

# Preload every module main.js needs, so the browser fetches them in parallel instead of one
# import level at a time.
IMPORT_RE = re.compile(r'''(?:^|\n)\s*(?:import|export)\b[^'"]*?from\s*['"](\.[^'"]+)['"]|(?:^|\n)\s*import\s*['"](\.[^'"]+)['"]''')
def module_graph(entry):
    seen, todo = [], [entry]
    while todo:
        f = todo.pop()
        if f in seen:
            continue
        seen.append(f)
        for m in IMPORT_RE.finditer(f.read_text()):
            dep = (f.parent / (m.group(1) or m.group(2))).resolve()
            if not dep.exists():
                sys.exit(f'{f.relative_to(root)}: import of missing module {dep}')
            todo.append(dep)
    return seen
entry = (dist / 'js' / 'main.js').resolve()
modules = sorted(p.relative_to(dist.resolve()).as_posix() for p in module_graph(entry) if p != entry)
index = (dist / 'index.html').read_text()
tag = '<script type="module" src="js/main.js"></script>'
assert tag in index
preload = ''.join(f'<link rel="modulepreload" href="{m}">\n' for m in modules)
(dist / 'index.html').write_text(index.replace(tag, preload + tag))

# Service worker: every file of the app, and a version that changes whenever one of them does.
files = sorted(p.relative_to(dist).as_posix() for p in dist.rglob('*')
               if p.is_file() and p.name != 'sw.js' and not p.name.startswith('LICENSE'))
version = hashlib.sha256(b''.join((dist / f).read_bytes() for f in files if f != 'config.js')).hexdigest()[:12]
sw = (src / 'sw.js').read_text().replace('@VERSION@', version).replace('/*@FILES@*/[]', json.dumps(['./' + f for f in files]))
(dist / 'sw.js').write_text(sw)

print(f'dist/: {len(files) + 1} files ({len(modules) + 1} modules), cache version {version}, sync {"on" if sync else "off"}'
      f'{", sign-up open" if config["allowSignup"] else ""}{", Turnstile" if config["turnstileSiteKey"] else ""}')
