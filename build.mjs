// Builds the app into dist/ (a static site: serve it over HTTPS from any host).
//
// src/ is copied as is (no bundling: the browser loads the ES modules directly). The build adds:
//   config.js      deployment settings, from environment variables (GitHub Actions variables in CI)
//   CSP            a Content-Security-Policy <meta> tag built from the same settings
//   privacy.html   the privacy page, filled in from the same variables
//   footer         source code and issue links
//   preloads       a modulepreload link for every module, so they download in parallel
//   icons          drawn by tools/icons.mjs
//   sw.js          with the list of files to cache and a version hash
//
// Usage: node build.mjs [--out DIR]
//
// Environment variables (all optional; without SUPABASE_URL the app keeps progress in the browser only):
//   SUPABASE_URL               https://<project>.supabase.co
//   SUPABASE_PUBLISHABLE_KEY   the project's publishable (or legacy anon) key; public by design
//   ALLOW_SIGNUP               "true": an unknown email creates an account on first sign-in
//   TURNSTILE_SITE_KEY         Cloudflare Turnstile site key (public); empty = no check on the sign-in form
//   PRIVACY_OPERATOR           who runs this copy, e.g. "Jane Doe, Luxembourg"
//   PRIVACY_CONTACT_EMAIL      address for privacy requests
//   PRIVACY_DATA_LOCATION      where Supabase stores the data, e.g. "Servers in Ireland (EU)."
//   PRIVACY_EMAIL_PROVIDER     who sends the sign-in emails, e.g. "Brevo (EU)"
//   PRIVACY_HOSTING            who hosts the files (default: GitHub Pages)
//   STAGING                    "true": a test copy (a Staging tag, and test tools in Options)
//   REPOSITORY_URL             source code link in the footer (in GitHub Actions: this repository, automatically)
import { createHash } from 'node:crypto';
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { writeAll as writeIcons } from './tools/icons.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, 'src');
const { values: args } = parseArgs({ options: { out: { type: 'string', default: join(root, 'dist') } } });
const dist = resolve(args.out);

const env = (name, fallback = '') => (process.env[name] || '').trim() || fallback;
const truthy = (v) => ['1', 'true', 'yes', 'on'].includes(v.toLowerCase());
const escape = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;' }[c]));
const fail = (msg) => { console.error(msg); process.exit(1); };
const read = (p) => readFileSync(p, 'utf8');
const posix = (p) => p.split(sep).join('/');
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

rmSync(dist, { recursive: true, force: true });
// Type declarations are for the type check only, not part of the site.
cpSync(src, dist, { recursive: true, filter: (p) => !p.endsWith('.d.ts') });

// ---------- Deployment settings ----------
const config = {
  supabaseUrl: env('SUPABASE_URL'),
  supabaseKey: env('SUPABASE_PUBLISHABLE_KEY'),
  allowSignup: truthy(env('ALLOW_SIGNUP')),
  turnstileSiteKey: env('TURNSTILE_SITE_KEY'),
  staging: truthy(env('STAGING')),
};
if (!!config.supabaseUrl !== !!config.supabaseKey) fail('Set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY, or neither.');
let supaOrigin = '';
if (config.supabaseUrl) {
  let u;
  try { u = new URL(config.supabaseUrl); } catch { u = null; }
  if (!u || !['https:', 'http:'].includes(u.protocol) || !['', '/'].includes(u.pathname) || u.search) fail('SUPABASE_URL must look like https://<project>.supabase.co');
  supaOrigin = u.origin;
}
writeFileSync(join(dist, 'config.js'),
  `// Generated by build.mjs from environment variables. Do not edit.\nwindow.SPACEDCUBE_CONFIG = ${JSON.stringify(config, null, 2)};\n`);

// ---------- Content Security Policy ----------
// As a <meta> tag (GitHub Pages cannot send headers). Scripts and connections only to this site,
// the sync server and, when used, Cloudflare Turnstile. Inline style attributes are allowed
// (the views use a few); inline scripts are not.
const turnstile = config.turnstileSiteKey ? 'https://challenges.cloudflare.com' : '';
const policy = {
  'default-src': ["'self'"],
  'script-src': ["'self'", turnstile],
  'style-src': ["'self'", "'unsafe-inline'"],
  'img-src': ["'self'", 'data:'],
  'font-src': ["'self'"],
  'connect-src': ["'self'", supaOrigin],
  'frame-src': [turnstile || "'none'"],
  'worker-src': ["'self'"],
  'manifest-src': ["'self'"],
  'object-src': ["'none'"],
  'base-uri': ["'self'"],
  'form-action': ["'self'"],
};
const csp = Object.entries(policy).map(([k, v]) => [k, ...v.filter(Boolean)].join(' ')).join('; ');
const CSP_PRIVACY = "default-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'none'; object-src 'none'; base-uri 'self'";
function addCsp(file, value) {
  const page = read(file);
  if (!page.includes('<!--@CSP@-->')) fail(`${file}: no CSP marker`);
  if (value.includes('"')) fail('CSP value must not contain double quotes');
  writeFileSync(file, page.replace('<!--@CSP@-->', `<meta http-equiv="Content-Security-Policy" content="${value}">`));
}
const indexPath = join(dist, 'index.html');
addCsp(indexPath, csp);

// ---------- Privacy page ----------
const sync = !!config.supabaseUrl;
const contact = env('PRIVACY_CONTACT_EMAIL');
const fill = {
  OPERATOR: escape(env('PRIVACY_OPERATOR', 'the people who published it')),
  CONTACT: contact ? `<a href="mailto:${escape(contact)}">${escape(contact)}</a>` : 'Ask the people who run this site.',
  DATA_LOCATION: escape(env('PRIVACY_DATA_LOCATION')),
  EMAIL_PROVIDER: escape(env('PRIVACY_EMAIL_PROVIDER', 'The email service of the sync server')),
  HOSTING: escape(env('PRIVACY_HOSTING', 'GitHub Pages (GitHub, United States, under the EU-US Data Privacy Framework)')),
};
let privacy = read(join(src, 'privacy.html')).replace(/\n<!-- Template:[\s\S]*?-->/, '');
for (const [block, keep] of [['SYNC', sync], ['TURNSTILE', sync && !!config.turnstileSiteKey]]) {
  privacy = privacy.replace(new RegExp(`<!--IF ${block}-->([\\s\\S]*?)<!--END ${block}-->`, 'g'), (_, inner) => (keep ? inner : ''));
}
for (const [k, v] of Object.entries(fill)) privacy = privacy.split(`{{${k}}}`).join(v);
if (privacy.includes('{{') || privacy.includes('<!--IF')) fail('unfilled privacy template');
writeFileSync(join(dist, 'privacy.html'), privacy);
addCsp(join(dist, 'privacy.html'), CSP_PRIVACY);

writeIcons(dist);

// ---------- Footer: source code and issue links, privacy ----------
let repo = env('REPOSITORY_URL');
if (!repo && env('GITHUB_REPOSITORY')) repo = `${env('GITHUB_SERVER_URL', 'https://github.com')}/${env('GITHUB_REPOSITORY')}`;
repo = repo.replace(/\/+$/, '');
if (repo && !/^https:\/\/[^\s"<>]+$/.test(repo)) fail('REPOSITORY_URL must be an https:// address');
const links = [
  ...(repo ? [`<a href="${escape(repo)}">Source code</a>`, `<a href="${escape(repo)}/issues">Report a problem or suggest an idea</a>`] : []),
  '<a href="privacy.html">Privacy</a>',
];
const footer = '<footer class="foot"><p>SpacedCube is free and open source (MIT licence). '
  + `<span class="foot-links">${links.map((a) => `<span>${a}</span>`).join('')}</span></p></footer>`;
writeFileSync(indexPath, read(indexPath).replace('<!--@FOOTER@-->', footer));

// ---------- Module preloads ----------
// Every module main.js needs, so the browser fetches them in parallel instead of one import level at a time.
const IMPORT_RE = /(?:^|\n)\s*(?:import|export)\b[^'"]*?from\s*['"](\.[^'"]+)['"]|(?:^|\n)\s*import\s*['"](\.[^'"]+)['"]/g;
function moduleGraph(entry) {
  const seen = new Set(), todo = [entry];
  while (todo.length) {
    const f = todo.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    for (const m of read(f).matchAll(IMPORT_RE)) {
      const dep = resolve(dirname(f), m[1] || m[2]);
      if (!existsSync(dep)) fail(`${relative(root, f)}: import of missing module ${dep}`);
      todo.push(dep);
    }
  }
  return [...seen];
}
const entry = join(dist, 'js', 'main.js');
const modules = moduleGraph(entry).filter((p) => p !== entry).map((p) => posix(relative(dist, p))).sort();
const tag = '<script type="module" src="js/main.js"></script>';
const index = read(indexPath);
if (!index.includes(tag)) fail('index.html: main.js script tag not found');
writeFileSync(indexPath, index.replace(tag, modules.map((m) => `<link rel="modulepreload" href="${m}">\n`).join('') + tag));

// ---------- Service worker ----------
// Every file of the app, and a version that changes whenever one of them does.
const files = walk(dist).map((p) => posix(relative(dist, p)))
  .filter((f) => f !== 'sw.js' && !f.split('/').pop().startsWith('LICENSE')).sort();
const hash = createHash('sha256');
for (const f of files) if (f !== 'config.js') hash.update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
writeFileSync(join(dist, 'sw.js'), read(join(src, 'sw.js'))
  .replace('@VERSION@', version)
  .replace('/*@FILES@*/[]', JSON.stringify(files.map((f) => './' + f))));

console.log(`${posix(relative(process.cwd(), dist)) || '.'}/: ${files.length + 1} files (${modules.length + 1} modules), cache version ${version}, `
  + `sync ${sync ? 'on' : 'off'}${config.allowSignup ? ', sign-up open' : ''}${config.turnstileSiteKey ? ', Turnstile' : ''}`);
